-- Nuvora analytics repair migration
-- Run this once in the Supabase SQL editor for the live Nuvora project.
-- This repairs PGRST205 when the table exists in the repository but not in the live database.

create table if not exists public.analytics_events (
  id bigint generated by default as identity primary key,
  event_name text not null,
  product_id uuid references public.products(id) on delete set null,
  session_id text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

alter table public.analytics_events enable row level security;

drop policy if exists "public analytics event insert" on public.analytics_events;
create policy "public analytics event insert"
on public.analytics_events
for insert to anon, authenticated
with check (char_length(event_name) between 1 and 80);

-- Make the newly-created table immediately visible to PostgREST.
notify pgrst, 'reload schema';
